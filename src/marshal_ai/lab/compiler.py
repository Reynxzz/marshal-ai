"""Fixed compiler: scenario spec -> standalone CARLA test script (flow 6).

The model never writes simulator code. This template does, so every generated test
has the same structure and can be reviewed as a short spec. The script drives the ego
car with CARLA's BehaviorAgent (the stand-in driving system), plays the actors, measures
the same metrics as the local simulator and prints them as one JSON line.

The stand-in is the plant's: BehaviorAgent plus the same brake for a prop in the car's path that
the plant's driving system has (carla_backend._object_in_path). Without it the lab tested a car
that drove into boxes: scene 3's case, SC-0142, failed no_contact against the very box the plant's
car stops for.

With --clip, a chase camera films the run into an mp4 (the design keeps a clip with every test
run); the runner uploads it and records its URI on the TestRun.

Blueprint ids for plant objects are proxies; confirm them on the server with
world.get_blueprint_library().filter("static.prop.*").
"""

from __future__ import annotations

from pprint import pformat
from string import Template

from marshal_ai.lab.spec import ScenarioSpec
from marshal_ai.plant import PlantMap

BLUEPRINTS = {
    "worker": "walker.pedestrian.0001",
    "forklift": "vehicle.carlamotors.carlacola",
    "parked_car": "vehicle.audi.a2",
    "pallet_stack": "static.prop.shoppingtrolley",
    "box": "static.prop.box01",                # an object in the lane, as in a stuck-car case
    "car": "vehicle.tesla.model3",
}

_TEMPLATE = Template('''"""Generated by Marshal from scenario $scenario_id. Do not edit: change the spec and recompile."""

import argparse
import json
import math
import queue
import subprocess

import carla
from agents.navigation.behavior_agent import BehaviorAgent

SPEC = $spec
POINTS = $points
ROUTE = $route
BLUEPRINTS = $blueprints
SUN = {"noon": 70.0, "dusk": 4.0, "night": -30.0}
ROADSIDE, WORKER_LAT, CROSSED_LAT = 3.5, 3.0, -5.0
LAB_ROLE = "marshal-lab"
# the plant's driving system brakes for a prop this far ahead of the car's centre, plus its
# braking distance, when it is within this far of the car's line (carla_backend: OBJECT_*)
OBJECT_STOP_M, OBJECT_LATERAL_M, OBJECT_DECEL_MS2 = $object_stop_m, $object_lateral_m, $object_decel_ms2
# Stopped this long for a prop that does not move, the run's outcome is settled: in the plant the
# car would ask for help (flow 2), and nobody answers in the lab. Running on to the timeout only
# spent the search's budget on a car standing still.
HELD_FOR_PROP_S = 15.0
CLIP_W, CLIP_H, CLIP_TICK_S = 640, 360, 0.2


def transform(name, forward=0.0, right=0.0):
    p = POINTS[name]
    if p is None:
        raise SystemExit(f"map point {name} has no CARLA transform (plant_map.yaml)")
    yaw = math.radians(p.get("yaw", 0.0))
    fx, fy = math.cos(yaw), math.sin(yaw)
    rx, ry = -fy, fx
    loc = carla.Location(x=p["x"] + fx * forward + rx * right, y=p["y"] + fy * forward + ry * right,
                         z=p.get("z", 0.5))
    return carla.Transform(loc, carla.Rotation(yaw=p.get("yaw", 0.0)))


def set_conditions(world):
    w = world.get_weather()
    w.sun_altitude_angle = SUN[SPEC["time_of_day"]]
    w.precipitation = 60.0 if SPEC["weather"] == "rain" else 0.0
    w.wetness = 60.0 if SPEC["weather"] == "rain" else 0.0
    w.fog_density = 50.0 if SPEC["weather"] == "fog" else 0.0
    world.set_weather(w)


def prop_in_path(world, ego):
    """A static prop in the ego car's path within its stopping distance, or None."""
    v = ego.get_velocity()
    speed = math.hypot(v.x, v.y)
    stop_m = OBJECT_STOP_M + speed * speed / (2 * OBJECT_DECEL_MS2)
    t = ego.get_transform()
    f = t.get_forward_vector()
    for a in world.get_actors().filter("static.prop.*"):
        o = a.get_location() - t.location
        ahead = o.x * f.x + o.y * f.y
        if 0 < ahead <= stop_m and abs(o.x * -f.y + o.y * f.x) <= OBJECT_LATERAL_M:
            return a
    return None


class Clip:
    """A chase camera on the ego car, encoded to mp4 as the run goes; one frame per CLIP_TICK_S."""

    def __init__(self, world, lib, ego, path):
        import imageio_ffmpeg
        bp = lib.find("sensor.camera.rgb")
        for k, val in (("image_size_x", CLIP_W), ("image_size_y", CLIP_H), ("sensor_tick", CLIP_TICK_S)):
            bp.set_attribute(k, str(val))
        if bp.has_attribute("role_name"):
            bp.set_attribute("role_name", LAB_ROLE)
        self.frames = queue.Queue()
        self.camera = world.spawn_actor(
            bp, carla.Transform(carla.Location(x=-8.0, z=4.0), carla.Rotation(pitch=-15.0)),
            attach_to=ego)
        self.camera.listen(self.frames.put)
        self.path, self.count = path, 0
        self.ffmpeg = subprocess.Popen(
            [imageio_ffmpeg.get_ffmpeg_exe(), "-loglevel", "error", "-y", "-f", "rawvideo",
             "-pix_fmt", "bgra", "-s", f"{CLIP_W}x{CLIP_H}", "-r", str(1.0 / CLIP_TICK_S), "-i", "-",
             "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast", path],
            stdin=subprocess.PIPE)

    def drain(self):
        while True:
            try:
                image = self.frames.get_nowait()
            except queue.Empty:
                return
            self.ffmpeg.stdin.write(bytes(image.raw_data))
            self.count += 1

    def close(self):
        self.camera.stop()
        self.drain()
        self.ffmpeg.stdin.close()
        self.ffmpeg.wait(timeout=60)
        return self.count


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--port", type=int, default=2000)
    ap.add_argument("--timeout", type=float, default=200.0,
                    help="simulated seconds before the run is abandoned; the "
                         "line_end->finishing route alone takes about 76 s")
    ap.add_argument("--clip", default=None, help="film the run into this mp4")
    args = ap.parse_args()

    client = carla.Client(args.host, args.port)
    client.set_timeout(20.0)
    world = client.get_world()
    settings = world.get_settings()
    settings.synchronous_mode, settings.fixed_delta_seconds = True, 0.05
    world.apply_settings(settings)
    set_conditions(world)
    lib = world.get_blueprint_library()
    spawned, events = [], []

    # A run killed by a timeout cannot reach its own cleanup, and a leaked actor
    # blocks the same spawn point for every later run. Every actor this script
    # creates is tagged, so stale ones can be cleared first.
    stale = [a for a in world.get_actors()
             if a.attributes.get("role_name") == LAB_ROLE]
    for a in stale:
        a.destroy()
    if stale:
        events.append(f"cleared {len(stale)} stale actor(s) from a previous run")
        world.tick()

    def blueprint(name):
        bp = lib.find(name)
        if bp.has_attribute("role_name"):
            bp.set_attribute("role_name", LAB_ROLE)
        return bp

    try:
        ego = world.spawn_actor(blueprint("vehicle.lincoln.mkz_2020"), transform(ROUTE[0]))
        spawned.append(ego)
        # A freshly spawned actor reports the origin until the server publishes one
        # frame, and BehaviorAgent reads the transform in its constructor. Without
        # this tick it plans from (0,0,0) and drives off the lane immediately.
        world.tick()
        agent = BehaviorAgent(ego, behavior="cautious")
        agent._behavior.max_speed = SPEC["ego"]["speed_kmh"]
        targets = list(ROUTE[1:])
        agent.set_destination(transform(targets[0]).location)
        contact = []
        col = world.spawn_actor(lib.find("sensor.other.collision"), carla.Transform(), attach_to=ego)
        spawned.append(col)
        col.listen(lambda e: contact.append(e.other_actor.type_id))
        clip = None
        if args.clip:
            try:
                clip = Clip(world, lib, ego, args.clip)
                spawned.append(clip.camera)
            except Exception as exc:      # a run without its clip is still a run
                events.append(f"no clip: {type(exc).__name__}: {exc}")

        occluders, movers = {}, []
        occluder_actors = {}
        for i, a in enumerate(SPEC["actors"]):
            if a.get("position") and a["type"] in ("forklift", "parked_car", "pallet_stack"):
                occluders[a["type"]] = a["position"]
        for i, a in enumerate(SPEC["actors"]):
            start = a.get("start") or ""
            candidates = []
            if start.startswith("behind:"):
                kind = start.split(":", 1)[1]
                at = occluders[kind]
                # "Behind" must clear the occluder's own body, or the spawn lands inside
                # it and fails. Step past its half-length, then widen if still blocked.
                hidden = occluder_actors.get(kind)
                half_len = hidden.bounding_box.extent.x if hidden is not None else 3.0
                base = half_len + 1.8
                candidates = [transform(at, forward=base + d, right=WORKER_LAT + r)
                              for d, r in ((0.0, 0.0), (1.5, 0.0), (0.0, 1.2), (3.0, 0.0), (1.5, 1.2))]
            elif a["type"] == "car" and a.get("state") == "braking":
                gap = (a.get("trigger") or {}).get("ego_distance_m", 10.0)
                candidates = [transform(ROUTE[0], forward=gap + 4.8)]
            else:
                lat = WORKER_LAT if a["type"] == "worker" else 0.0 if a["type"] == "box" else ROADSIDE
                where = a.get("position") or start
                candidates = [transform(where, right=lat),
                              transform(where, right=lat, forward=4.0),
                              transform(where, right=lat + 1.5)]
            actor = tf = None
            for cand in candidates:
                actor = world.try_spawn_actor(blueprint(BLUEPRINTS[a["type"]]), cand)
                if actor is not None:
                    tf = cand
                    break
            if actor is None:
                raise SystemExit(f"could not spawn actor {i} ({a['type']}) at any of "
                                 f"{len(candidates)} candidate placements")
            if a["type"] in ("forklift", "parked_car", "pallet_stack"):
                occluder_actors[a["type"]] = actor
            spawned.append(actor)
            moving = a.get("state") in ("moving", "crossing") or (a["type"] == "worker" and (a.get("trigger") or start.startswith("behind:")))
            movers.append({"i": i, "spec": a, "actor": actor, "moving": moving, "triggered": False,
                           "start": tf, "person": a["type"] == "worker"})

        min_gap_p = min_gap_v = 99.0
        near_speed = max_speed = 0.0
        t, reached, braked_for, held_s, noted = 0.0, False, None, 0.0, set()
        while t < args.timeout:
            world.tick()
            t += 0.05
            if clip is not None:
                clip.drain()
            ego_loc = ego.get_location()
            v = ego.get_velocity()
            speed = 3.6 * math.sqrt(v.x ** 2 + v.y ** 2 + v.z ** 2)
            max_speed = max(max_speed, speed)
            for m in movers:
                a, act = m["spec"], m["actor"]
                d = act.get_location().distance(ego_loc)
                gap = max(0.0, d - ego.bounding_box.extent.x - act.bounding_box.extent.x)
                if m["person"]:
                    min_gap_p = min(min_gap_p, gap)
                    if gap < 2.0:
                        near_speed = max(near_speed, speed)
                elif m["moving"] or a["type"] == "car":
                    min_gap_v = min(min_gap_v, gap)
                if a["type"] == "car" and a.get("state") == "braking":
                    ctrl = carla.VehicleControl(throttle=0.35 if t < 3.0 else 0.0, brake=0.0 if t < 3.0 else 1.0)
                    act.apply_control(ctrl)
                    continue
                if not m["moving"]:
                    continue
                trig = (a.get("trigger") or {}).get("ego_distance_m", 8.0)
                if not m["triggered"] and d <= trig:
                    m["triggered"] = True
                    events.append(f"t={t:.1f}s actor {m['i']} starts moving")
                if m["triggered"]:
                    left = m["start"].get_right_vector() * -1.0
                    spd = a.get("walk_speed_ms") or (a.get("speed_kmh") or 5.0) / 3.6
                    if m["person"]:
                        act.apply_control(carla.WalkerControl(direction=left, speed=spd))
            if agent.done():
                targets.pop(0)
                if not targets:
                    reached = True
                    break
                agent.set_destination(transform(targets[0]).location)
            prop = prop_in_path(world, ego)
            if prop is not None:
                if braked_for != prop.id:
                    held_s = 0.0
                    if prop.id not in noted:      # the stop releases and re-applies as it slows
                        noted.add(prop.id)
                        events.append(f"t={t:.1f}s braked for {prop.type_id} in the path")
                braked_for = prop.id
                ego.apply_control(carla.VehicleControl(throttle=0.0, brake=1.0))
                held_s += 0.05 if speed < 0.5 else 0.0
                if held_s >= HELD_FOR_PROP_S:
                    events.append(f"t={t:.1f}s still stopped for {prop.type_id} after "
                                  f"{HELD_FOR_PROP_S:.0f} s: would ask for help; run ended")
                    break
                continue
            braked_for = None
            ego.apply_control(agent.run_step())

        if contact:      # what was touched: a failed no_contact is unreadable without it
            events.append("contact with " + ", ".join(sorted(set(contact))))
        metrics = {
            "no_contact": 0.0 if contact else 1.0,
            "reached_goal": 1.0 if reached else 0.0,
            "min_gap_to_person_m": round(min_gap_p, 2),
            "min_gap_to_vehicle_m": round(min_gap_v, 2),
            "speed_near_person_kmh": round(near_speed, 2),
            "max_speed_kmh": round(max_speed, 2),
            "time_to_goal_s": round(t, 1),
        }
        result = {"metrics": metrics, "events": events,
                  "triggered": [m["i"] for m in movers if m["triggered"]]}
        if clip is not None:
            spawned.remove(clip.camera)
            result["clip_frames"] = clip.close()
            clip.camera.destroy()
            result["clip"] = args.clip
        print(json.dumps(result))
    finally:
        for actor in reversed(spawned):
            actor.destroy()
        settings.synchronous_mode = False
        world.apply_settings(settings)


if __name__ == "__main__":
    main()
''')


def compile_spec(spec: ScenarioSpec, plant_map: PlantMap) -> str:
    route = [spec.ego.waypoints[0]]
    for a, b in zip(spec.ego.waypoints, spec.ego.waypoints[1:]):
        route += plant_map.route(a, b)[1:]
    names = set(route) | {a.position for a in spec.actors if a.position} | \
        {a.start for a in spec.actors if a.start and not a.start.startswith("behind:")}
    points = {n: plant_map.points[n].carla for n in sorted(names)}
    from marshal_ai.driving import carla_backend as plant_driving   # constants only; no CARLA needed
    return _TEMPLATE.substitute(
        object_stop_m=plant_driving.OBJECT_STOP_M,
        object_lateral_m=plant_driving.OBJECT_LATERAL_M,
        object_decel_ms2=plant_driving.OBJECT_DECEL_MS2,
        scenario_id=spec.id,
        spec=pformat(spec.model_dump(mode="json"), sort_dicts=False),
        points=pformat(points),
        route=pformat(route),
        blueprints=pformat(BLUEPRINTS),
    )
