"""Fixed compiler: scenario spec -> Scenic program for MetaDrive (flow 6 on a laptop).

The model never writes simulator code. This template does, so every generated test has the same
structure and can be reviewed as a short spec. Positions are computed here from the plant map and
written into the program as numbers; the program calls `marshal_ai.lab.scenic_world` for the
driving system under test and for the metrics.
"""

from __future__ import annotations

from string import Template

from marshal_ai.lab.scenic_world import layout, layout_to_json, scenic_heading
from marshal_ai.lab.sim import TIMEOUT_S
from marshal_ai.lab.spec import ScenarioSpec
from marshal_ai.plant import PlantMap
from marshal_ai.plant.roadnet import NET_FILE, XODR_FILE

_TEMPLATE = Template('''"""Generated by Marshal from scenario $scenario_id. Do not edit: change the spec and recompile.

$description
Time of day: $time_of_day. Weather: $weather. Ego route: $route at $speed km/h.
Pass criteria: $criteria
"""

param map = r'$xodr'
param sumo_map = r'$net'
param render = 0
param real_time = 0
param timestep = $dt
param profile = None
param clip = None
model scenic.simulators.metadrive.model

from marshal_ai.lab import scenic_world as mw

LAYOUT = mw.layout_from_json(r"""$layout""")
DT = $dt
DRIVER = mw.EgoDriver(LAYOUT, globalParameters.profile)
MONITOR = mw.Monitor(LAYOUT, globalParameters.clip)


behavior DrivingSystem():
    while True:
        MONITOR.step(self, simulation().objects, DRIVER, DT, simulation())
        steer, throttle, brake = DRIVER.control(self, simulation().objects, DT)
        take SetSteerAction(steer), SetThrottleAction(throttle), SetBrakeAction(brake)

behavior Parked():
    while True:
        take SetThrottleAction(0), SetBrakeAction(1)

behavior Cross(placed):
    while not mw.triggered(self, ego, placed):
        wait
    MONITOR.mark_triggered(placed)
    take SetWalkingDirectionAction(mw.scenic_heading(placed.cross_yaw)), SetWalkingSpeedAction(placed.speed_ms)
    while not mw.crossed(self, placed):
        wait
    take SetWalkingSpeedAction(0)
    while True:
        wait

behavior DriveAcross(placed):
    while not mw.triggered(self, ego, placed):
        take SetThrottleAction(0), SetBrakeAction(1)
    MONITOR.mark_triggered(placed)
    while not mw.crossed(self, placed):
        if self.speed < placed.speed_ms:
            take SetSteerAction(0), SetThrottleAction(0.3), SetBrakeAction(0)
        else:
            take SetSteerAction(0), SetThrottleAction(0), SetBrakeAction(0)
    while True:
        take SetThrottleAction(0), SetBrakeAction(1)

behavior Lead(placed):
    lead = mw.LeadCar(LAYOUT, placed)
    MONITOR.mark_triggered(placed)
    while True:
        steer, throttle, brake = lead.control(self, DT)
        take SetSteerAction(steer), SetThrottleAction(throttle), SetBrakeAction(brake)


ego = new Car at ($ego_x, $ego_y), facing $ego_h, with behavior DrivingSystem(),
    with regionContainedIn everywhere, with marshalId "ego", with marshalKind "vehicle", with marshalIndex -1
$actors

terminate when MONITOR.done
terminate after $timeout seconds
record final MONITOR.finish(simulation(), DRIVER) as result
''')


def _actor_line(p) -> str:
    name = f"{p.type}-{p.index}"
    if p.kind == "person":
        cls, beh = "Pedestrian", f"Cross(LAYOUT.actors[{p.index}])" if p.moves else None
    elif p.brake_at_s is not None:
        cls, beh = "Car", f"Lead(LAYOUT.actors[{p.index}])"
    else:
        cls, beh = "Car", f"DriveAcross(LAYOUT.actors[{p.index}])" if p.moves else "Parked()"
    facing = p.cross_yaw if (p.moves and p.kind == "vehicle" and p.cross_yaw is not None) else p.yaw
    parts = [f"a{p.index} = new {cls} at ({p.x:.3f}, {p.y:.3f}), facing {scenic_heading(facing):.4f}"]
    if beh:
        parts.append(f"with behavior {beh}")
    parts += ["with regionContainedIn everywhere", f'with marshalId "{name}"',
              f'with marshalKind "{p.kind}"', f"with marshalIndex {p.index}"]
    return ",\n    ".join(parts)


def compile_scenic(spec: ScenarioSpec, plant_map: PlantMap, dt: float = 0.1) -> str:
    lay = layout(spec, plant_map)
    ex, ey, eyaw = lay.ego
    return _TEMPLATE.substitute(
        scenario_id=spec.id,
        description=spec.description or f"Scenario {spec.id} in zone {spec.map_zone}.",
        time_of_day=spec.time_of_day.value, weather=spec.weather.value,
        route=spec.ego.route, speed=spec.ego.speed_kmh, criteria="; ".join(spec.pass_criteria),
        xodr=str(XODR_FILE), net=str(NET_FILE), dt=dt, layout=layout_to_json(lay),
        ego_x=f"{ex:.3f}", ego_y=f"{ey:.3f}", ego_h=f"{scenic_heading(eyaw):.4f}",
        actors="\n".join(_actor_line(p) for p in lay.actors),
        timeout=int(TIMEOUT_S),
    )

