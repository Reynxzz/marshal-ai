#!/usr/bin/env python3
"""Build the plant's own world from OpenDRIVE on the CARLA server, and check it can carry the demo.

    python3 scripts/plant_xodr.py --out /tmp/marshal_plant.xodr
    python3 scripts/load_plant_world.py --xodr /tmp/marshal_plant.xodr --check --out /tmp/marshal-plant-world

Builds the world (client.generate_opendrive_world, walls along the road edges), resolves each plant
point from (road, lane, s) to a CARLA transform, and with --check: drives a car with BehaviorAgent
from the line end round to yard slot Y5, photographs the plant, and keeps the server ticking for a
minute to see it stays up (Town05_Opt with layers unloaded did not). --restore loads Town05 after.
"""

from __future__ import annotations

import argparse
import json
import math
import queue
import time
from pathlib import Path

import carla


def emit(obj):
    print(json.dumps(obj), flush=True)


def build(client, xodr: str):
    params = carla.OpendriveGenerationParameters(
        # No walls: CARLA puts one along every road edge, the paving across the middle included, and lane
        # C crosses that paving. The plant's perimeter fence comes from the dressing.
        vertex_distance=2.0, max_road_length=500.0, wall_height=0.0, additional_width=0.6,
        smooth_junctions=True, enable_mesh_visibility=True, enable_pedestrian_navigation=True)
    world = client.generate_opendrive_world(xodr, params)
    world.wait_for_tick(30.0)
    return world


def resolve(m: carla.Map, points: dict) -> dict:
    out = {}
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from plant_xodr import physical
    for name, (road, lane, s) in points.items():
        road, s = physical(road, s)             # roads 1 and 5 are split where lane C meets them
        wp = m.get_waypoint_xodr(road, lane, s)
        if wp is None:
            out[name] = None
            continue
        t = wp.transform
        out[name] = {"x": round(t.location.x, 2), "y": round(t.location.y, 2), "z": round(t.location.z + 0.5, 2),
                     "yaw": round(t.rotation.yaw, 1), "lane_type": str(wp.lane_type)}
    return out


def write_plant_map(pts: dict, template: Path, out: Path) -> None:
    """plant_map.yaml with every point's `carla` block from this world; bays and slots pull over."""
    import re
    lines = ["# Generated by scripts/load_plant_world.py --write-map: plant_map.yaml with every point's",
             "# CARLA transform on the plant's own world (scripts/plant_xodr.py). Do not edit by hand.", ""]
    written = 0
    for line in template.read_text().splitlines():
        # points line up their fields with spaces, so any run of spaces may come before `carla:`
        m = re.match(r"^(  )([\w.]+):(\s+)\{(.*?),\s*carla: \{.*\}\}\s*$", line)
        if m and m.group(2) in pts and pts[m.group(2)]:
            p = pts[m.group(2)]
            off = ", pull_over: true" if p["lane_type"] in ("Shoulder", "Parking") else ""
            line = (f"{m.group(1)}{m.group(2)}:{m.group(3)}{{{m.group(4)}, carla: {{x: {p['x']}, y: {p['y']}, "
                    f"z: {p['z']}, yaw: {p['yaw']}{off}}}}}")
            written += 1
        elif line.startswith("carla_map:"):
            line = "carla_map: OpenDriveMap   # the plant's own world, MARSHAL_CARLA_MAP=MarshalPlant"
        lines.append(line)
    if written != len([v for v in pts.values() if v]):
        raise SystemExit(f"wrote {written} of {len(pts)} points; the template's point lines did not all match")
    out.write_text("\n".join(lines) + "\n")


def photo(world, loc, rot, path: Path, size=(1280, 720), fov=85):
    bp = world.get_blueprint_library().find("sensor.camera.rgb")
    bp.set_attribute("image_size_x", str(size[0]))
    bp.set_attribute("image_size_y", str(size[1]))
    bp.set_attribute("fov", str(fov))
    cam = world.spawn_actor(bp, carla.Transform(loc, rot))
    q: queue.Queue = queue.Queue()
    cam.listen(q.put)
    img = None
    for _ in range(60):
        if world.get_settings().synchronous_mode:
            world.tick()
        try:
            img = q.get(timeout=1.0)
        except queue.Empty:
            continue
        if img.frame > 0:
            break
    cam.stop()
    cam.destroy()
    if img is not None:
        img.save_to_disk(str(path))
    return img is not None


def ffmpeg(path: Path, w: int, h: int, fps: float):
    import subprocess
    import imageio_ffmpeg
    return subprocess.Popen([imageio_ffmpeg.get_ffmpeg_exe(), "-loglevel", "error", "-y", "-f", "rawvideo",
                             "-pix_fmt", "bgra", "-s", f"{w}x{h}", "-r", f"{fps:g}", "-i", "-", "-c:v", "libx264",
                             "-preset", "veryfast", "-pix_fmt", "yuv420p", str(path)], stdin=subprocess.PIPE)


def drive(world, m, pts: dict, out: Path, timeout_s: float = 240.0, film: Path | None = None) -> dict:
    from agents.navigation.behavior_agent import BehaviorAgent

    start, goal = pts["line_end"], pts["yard.Y5"]
    bp = world.get_blueprint_library().find("vehicle.lincoln.mkz_2020")
    bp.set_attribute("color", "0,80,200")
    car = world.spawn_actor(bp, carla.Transform(carla.Location(start["x"], start["y"], start["z"]),
                                                carla.Rotation(yaw=start["yaw"])))
    original = world.get_settings()                    # a copy: restored at the end
    settings = world.get_settings()
    settings.synchronous_mode, settings.fixed_delta_seconds = True, 0.05
    world.apply_settings(settings)
    cams, writer, frames = [], None, queue.Queue()
    try:
        world.tick()
        if film is not None:
            # a camera riding behind the car (attached, so it is never moved by hand), and an overview
            # from above held for the first seconds
            bp_cam = world.get_blueprint_library().find("sensor.camera.rgb")
            bp_cam.set_attribute("image_size_x", "1280"); bp_cam.set_attribute("image_size_y", "720")
            bp_cam.set_attribute("fov", "90")
            chase = world.spawn_actor(bp_cam, carla.Transform(carla.Location(x=-9, z=4.5), carla.Rotation(pitch=-14)),
                                      attach_to=car)
            top = world.spawn_actor(bp_cam, carla.Transform(carla.Location(60, -52, 120), carla.Rotation(pitch=-90)))
            for c in (chase, top):
                c.listen(lambda img, name=("chase" if c is chase else "top"): frames.put((name, img)))
            cams = [chase, top]
            writer = ffmpeg(film, 1280, 720, 20.0)
        agent = BehaviorAgent(car, behavior="cautious")
        agent.set_destination(carla.Location(goal["x"], goal["y"], goal["z"]))
        ticks, reached, travelled, last = 0, False, 0.0, car.get_location()
        while ticks < timeout_s / 0.05:
            car.apply_control(agent.run_step())
            frame = world.tick()
            ticks += 1
            if writer is not None:
                got = {}
                while len(got) < 2:
                    name, img = frames.get(timeout=10.0)
                    if img.frame >= frame:
                        got[name] = img
                # overview for the first 4 s, then the chase camera, every other frame (2x speed)
                if ticks % 2 == 0:
                    writer.stdin.write(bytes((got["top"] if ticks <= 80 else got["chase"]).raw_data))
            here = car.get_location()
            travelled += here.distance(last)
            last = here
            if agent.done():
                reached = True
                break
        end = car.get_location()
        miss = math.dist((end.x, end.y), (goal["x"], goal["y"]))
        # the car on the bend and in the yard, from above and behind
        photo(world, end + carla.Location(x=-14, z=9), carla.Rotation(pitch=-28, yaw=0), out / "car_in_yard.png")
        return {"reached": reached, "sim_s": round(ticks * 0.05, 1), "travelled_m": round(travelled, 1),
                "end_off_goal_m": round(miss, 2), "film": str(film) if film else None}
    finally:
        if writer is not None:
            writer.stdin.close()
            writer.wait()
        for c in cams:
            c.stop()
            c.destroy()
        car.destroy()
        world.apply_settings(original)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xodr", type=Path, default=Path("/tmp/marshal_plant.xodr"))
    ap.add_argument("--out", type=Path, default=Path("/tmp/marshal-plant-world"))
    ap.add_argument("--check", action="store_true", help="drive a car round, photograph, watch stability")
    ap.add_argument("--restore", action="store_true", help="load Town05 again at the end")
    ap.add_argument("--film", action="store_true", help="with --check: film the drive to OUT/drive.mp4")
    ap.add_argument("--no-build", action="store_true", help="use the plant world already loaded (and dressed)")
    ap.add_argument("--write-map", type=Path, default=None,
                    help="write a plant map for this world here (plant_map.yaml with these transforms)")
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--port", type=int, default=2000)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    client = carla.Client(args.host, args.port)
    client.set_timeout(180.0)
    world = client.get_world() if args.no_build else build(client, args.xodr.read_text())
    m = world.get_map()
    points = json.loads(args.xodr.with_suffix(".points.json").read_text())
    pts = resolve(m, points)
    (args.out / "points.json").write_text(json.dumps(pts, indent=1))
    emit({"type": "plant_world.built", "map": m.name, "points": sum(v is not None for v in pts.values()),
          "missing": [k for k, v in pts.items() if v is None]})
    if args.write_map:
        template = Path(__file__).resolve().parent.parent / "src/marshal_ai/plant/plant_map.yaml"
        write_plant_map(pts, template, args.write_map)
        emit({"type": "plant_world.map_written", "path": str(args.write_map)})
    if args.check:
        weather = world.get_weather()
        weather.sun_altitude_angle = 45.0
        world.set_weather(weather)
        g = pts["inspection_gate"]
        photo(world, carla.Location(g["x"] - 30, g["y"] + 12, 7), carla.Rotation(pitch=-12, yaw=-15), args.out / "along_south.png")
        photo(world, carla.Location(60, -52, 150), carla.Rotation(pitch=-90), args.out / "top.png", (1000, 1000), 90)
        emit({"type": "plant_world.drive", **drive(world, m, pts, args.out,
                                                   film=args.out / "drive.mp4" if args.film else None)})
        alive = 0
        for _ in range(6):
            time.sleep(10)
            world.wait_for_tick(20.0)
            alive += 10
        emit({"type": "plant_world.stable", "seconds": alive})
    if args.restore:
        client.load_world("Town05")
        emit({"type": "plant_world.restored", "map": "Town05"})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
